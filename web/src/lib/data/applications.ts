export const applicationById = (id: string): Application | undefined =>
  applications.find((application) => application.id === id);

export const primaryApplicationId = "GS-2026-00142";

export const activeApplications = applications.filter(
  (application) => application.state !== "approved",
);

export const completedApplications = applications.filter(
  (application) => application.state === "approved",
);

/** Stage completion ratio, used for progress indicators. */
export function workflowProgress(application: Application): number {
  if (application.steps.length === 0) return 0;
  const done = application.steps.filter((step) => step.state === "approved").length;
  return Math.round((done / application.steps.length) * 100);
}

/** True when at least one stage is held by an unmet upstream dependency. */
export function hasBlockedStage(application: Application): boolean {
  return application.steps.some((step) => step.state === "blocked");
}

export interface OpenStage {
  applicationId: string;
  applicationTitle: string;
  step: WorkflowStep;
}

export function openStages(list: Application[] = applications): OpenStage[] {
  return list
    .flatMap((application) =>
      application.steps
        .filter((step) => step.state !== "approved")
        .map((step) => ({
          applicationId: application.id,
          applicationTitle: application.title,
          step,
        })),
    )
    .sort((a, b) => a.step.order - b.step.order);
}

export function pendingApprovalCount(list: Application[] = applications): number {
  return openStages(list).filter((entry) => entry.step.state !== "blocked").length;
}

export function completedApprovalCount(list: Application[] = applications): number {
  return list.reduce(
    (total, application) =>
      total + application.steps.filter((step) => step.state === "approved").length,
    0,
  );
}
